"""Generate ``src/wow/_sync`` from ``src/wow/_async``.

The async code is the source of truth. Run ``uv run scripts/unasync.py`` after changing it; CI runs
``uv run scripts/unasync.py --check`` to fail when the generated code is stale.
"""

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "wow" / "_async"
TARGET = ROOT / "src" / "wow" / "_sync"

SUBSTITUTIONS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(pattern), replacement)
    for pattern, replacement in [
        (r"\basync context manager\b", "context manager"),
        (r"\bAsync client\b", "Client"),
        (r"\basync client\b", "client"),
        (r"\bAsync([A-Z]\w*)", r"\1"),
        (r"\basync_sleep\b", "sleep"),
        (r"\baclose\b", "close"),
        (r"\b__aenter__\b", "__enter__"),
        (r"\b__aexit__\b", "__exit__"),
        (r"\basync def\b", "def"),
        (r"\basync with\b", "with"),
        (r"\basync for\b", "for"),
        (r"\bawait ", ""),
        (r"\bwow\._async\b", "wow._sync"),
    ]
]


def unasync_source(source: str, relative: Path) -> str:
    """Rewrite one async module as its sync twin."""
    for pattern, replacement in SUBSTITUTIONS:
        source = pattern.sub(replacement, source)
    header = f"# Generated by scripts/unasync.py from src/wow/_async/{relative.as_posix()}. Do not edit.\n"
    return header + source


def generate(target: Path) -> None:
    """Write the sync package into ``target`` and format it like the rest of the code."""
    for path in sorted(SOURCE.rglob("*.py")):
        relative = path.relative_to(SOURCE)
        destination = target / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(unasync_source(path.read_text(encoding="utf-8"), relative), encoding="utf-8")
    ruff = [sys.executable, "-m", "ruff"]
    config = ["--config", str(ROOT / "pyproject.toml")]
    subprocess.run([*ruff, "check", "--quiet", *config, "--select", "I", "--fix", str(target)], check=True)
    subprocess.run([*ruff, "format", "--quiet", *config, str(target)], check=True)


def snapshot(directory: Path) -> dict[Path, str]:
    """Map each Python file under ``directory`` to its contents."""
    return {path.relative_to(directory): path.read_text(encoding="utf-8") for path in directory.rglob("*.py")}


def main() -> int:
    """Regenerate the sync package, or with ``--check`` report whether it is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of writing when the output would change")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as scratch:
        generated = Path(scratch) / "_sync"
        generate(generated)
        expected = snapshot(generated)
    current = snapshot(TARGET) if TARGET.exists() else {}
    stale = sorted(path for path in expected.keys() | current.keys() if expected.get(path) != current.get(path))
    if args.check:
        if stale:
            print("src/wow/_sync is stale; run `uv run scripts/unasync.py`:", *map(str, stale), sep="\n  ")
            return 1
        return 0
    for path in stale:
        destination = TARGET / path
        if path in expected:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(expected[path], encoding="utf-8")
        else:
            destination.unlink()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
